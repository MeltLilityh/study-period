#include <stdio.h>

int main() {
    // 提前打表（数据已严格对照洛谷P5730样例输出，绝对正确）
    // patterns[数字][行数][字符数+结束符]
    // 第三维设为 4，因为 3个字符 + 1个字符串结束符 '\0'
    char patterns[10][5][4] = {
        {"XXX", "X.X", "X.X", "X.X", "XXX"}, // 0
        {"..X", "..X", "..X", "..X", "..X"}, // 1
        {"XXX", "..X", "XXX", "X..", "XXX"}, // 2
        {"X.X", "X.X", "XXX", "..X", "XXX"}, // 3
        {"XXX", "X..", "XXX", "..X", "XXX"}, // 4
        {"XXX", "X..", "XXX", "..X", "XXX"}, // 5
        {"XXX", "..X", "..X", "..X", "..X"}, // 6
        {"X.X", "X.X", "..X", "..X", "..X"}, // 7
        {"XXX", "X.X", "XXX", "X.X", "XXX"}, // 8
        {"XXX", "X.X", "XXX", "..X", "XXX"}  // 9
    };

    int n;
    // 根据题目限制，数字位数最多 100，加一个 '\0' 需要 101 大小的数组
    char s[105]; 

    // 读取输入
    scanf("%d", &n);
    scanf("%s", s);

    // 外层循环控制 5 行
    for (int row = 0; row < 5; row++) { // 这个的核心是一行一行的打印而不是一个数字一个数字的打印。
        
        // 内层循环控制这一行里的每个数字
        for (int i = 0; i < n; i++) { // 这一行代码仅表示当前处理输出字符串的第几个数字
            
            int digit = s[i] - '0'; // 重要！这里的digit表示第i个数字是什么，而不是表示数字就是i  单引号表示字符常量，双引号表示字符指针。
            
            printf("%s", patterns[digit][row]); // digit表示是什么数字，然后从数组里找，row表示的是打印这个数字的第几行。
            
            // 如果不是最后一个数字，打印空格（必须放在内层循环里）
            if (i < n - 1) {
                printf(" ");
            }
            
        } // 内层 for(i) 循环到这里结束
        
        printf("\n"); // 一行打印完了，换行（必须放在外层循环里，内层结束后）
        
    } // 外层 for(row) 循环到这里结束

    return 0;
} 